import * as fs from 'node:fs';
import * as path from 'node:path';
import { ConanCli, ProfileInstallResult } from './conanCli';
import { ConanProject } from './conanProject';
import { computeInstallFingerprint } from './fingerprint';
import { FolderStateStore } from './settings';
import {
  canWriteUserPresets,
  readConfigurePresetNames,
  readUserPresetsIncludes,
  userPresetsPath,
  writeUserPresets,
} from './userPresetsFile';

export type SyncOutcome =
  /** The last install is still current; nothing ran. */
  | 'upToDate'
  /** Every profile installed and CMakeUserPresets.json is current. */
  | 'installed'
  /** At least one profile failed; presets were published for the ones that succeeded. */
  | 'partiallyFailed'
  /** A hand-written CMakeUserPresets.json is in the way; nothing ran. */
  | 'userPresetsNotOwned';

export interface SyncResult {
  readonly outcome: SyncOutcome;
  readonly profiles: readonly ProfileInstallResult[];
  /** Configure presets now available through CMakeUserPresets.json, in profile order. */
  readonly configurePresetNames: readonly string[];
}

export function isUpToDate(project: ConanProject, store: FolderStateStore): boolean {
  const state = store.load(project.rootDirectory);
  if (state.installFingerprint !== computeInstallFingerprint(project, state.hostProfiles, state.buildProfile)) {
    return false;
  }

  const includes = readUserPresetsIncludes(project.rootDirectory);
  return includes.length > 0 && includes.every(file => fs.existsSync(file));
}

/** Configure presets from the files CMakeUserPresets.json currently includes. */
export function currentConfigurePresetNames(projectDirectory: string): string[] {
  return readUserPresetsIncludes(projectDirectory).flatMap(readConfigurePresetNames);
}

/**
 * Brings a project's Conan dependencies up to date for the profiles in its saved state.
 * CMakeUserPresets.json is written once at the end, so CMake Tools reloads once. Keeping CMake
 * Tools from configuring in the meantime is the caller's job (see cmakeTools.ts).
 */
export async function syncDependencies(
  project: ConanProject,
  store: FolderStateStore,
  cli: ConanCli,
  options: { force: boolean; onLine: (line: string) => void; signal?: AbortSignal },
): Promise<SyncResult> {
  const directory = project.rootDirectory;
  const { onLine } = options;

  if (!options.force && isUpToDate(project, store)) {
    return { outcome: 'upToDate', profiles: [], configurePresetNames: currentConfigurePresetNames(directory) };
  }

  if (!canWriteUserPresets(directory)) {
    onLine(`${userPresetsPath(directory)} wasn't generated by Conan, so it won't be overwritten. `
      + 'Delete or rename it to let this extension manage it.');
    return { outcome: 'userPresetsNotOwned', profiles: [], configurePresetNames: [] };
  }

  const state = store.load(directory);
  const results: ProfileInstallResult[] = [];

  // Sequential on purpose: concurrent installs into the same Conan cache aren't safe.
  for (const profile of state.hostProfiles) {
    options.signal?.throwIfAborted();
    onLine(`========== conan install: profile '${profile}' ==========`);
    results.push(await cli.install(
      { projectDirectory: directory, hostProfile: profile, buildProfile: state.buildProfile },
      onLine,
      options.signal));
  }

  for (const result of results) {
    if (result.exitCode === 0 && !(result.presetsFile && fs.existsSync(result.presetsFile))) {
      onLine(`Warning: profile '${result.profile}' produced no CMakePresets.json. `
        + 'Does the conanfile use the CMakeToolchain generator?');
    }
  }

  let presets = results
    .filter(r => r.exitCode === 0 && r.presetsFile && fs.existsSync(r.presetsFile))
    .map(r => r.presetsFile!);

  const allSucceeded = results.every(r => r.exitCode === 0);
  if (!allSucceeded) {
    // Keep the presets of failed profiles from their last good install rather than dropping them.
    const kept = readUserPresetsIncludes(directory).filter(file => fs.existsSync(file));
    presets = unique([...kept, ...presets]);
  }

  writeUserPresets(directory, presets);

  const latest = store.load(directory);
  latest.installFingerprint = allSucceeded
    ? computeInstallFingerprint(project, latest.hostProfiles, latest.buildProfile)
    : undefined;
  await store.save(directory, latest);

  return {
    outcome: allSucceeded ? 'installed' : 'partiallyFailed',
    profiles: results,
    configurePresetNames: presets.flatMap(readConfigurePresetNames),
  };
}

function unique(files: string[]): string[] {
  const seen = new Set<string>();
  return files.filter(file => {
    const resolved = path.resolve(file);
    const key = process.platform === 'win32' ? resolved.toLowerCase() : resolved;
    return seen.has(key) ? false : (seen.add(key), true);
  });
}
